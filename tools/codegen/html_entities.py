"""Write `fav-core/src/pyhtml/entities.rs` from Python's `html.entities.html5`.

    UV_PYTHON=3.12 uv run python tools/codegen/html_entities.py [--check]

The table is data, not logic, so it is generated rather than typed. The Rust tests also
compare it with the `html/entities.json` golden, so a stale file fails CI either way.
"""

from __future__ import annotations

import argparse
import sys
from html.entities import html5
from pathlib import Path

TARGET = Path(__file__).resolve().parents[2] / 'crates' / 'fav-core' / 'src' / 'pyhtml' / 'entities.rs'


def _rust_str(text: str) -> str:
    return '"' + ''.join(f'\\u{{{ord(ch):x}}}' for ch in text) + '"'


def render() -> str:
    # Names are ASCII letters, digits and `;`; values are escaped so the file stays ASCII.
    if not all(name.isascii() and name.replace(';', '').isalnum() for name in html5):
        msg = 'an entity name needs escaping'
        raise SystemExit(msg)
    lines = [
        '//! `html.entities.html5` from Python 3.12, generated by `tools/codegen/html_entities.py`; do not edit.',
        '//!',
        '//! Sorted by name (byte order) for binary search. Names without a trailing `;` are the',
        "//! legacy ones HTML5 also accepts bare, exactly as in Python's table.",
        '',
        f'pub(super) static ENTITIES: [(&str, &str); {len(html5)}] = [',
    ]
    lines.extend(f'    ("{name}", {_rust_str(value)}),' for name, value in sorted(html5.items()))
    lines.append('];')
    return '\n'.join(lines) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the file differs instead of writing it')
    args = parser.parse_args()
    rendered = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != rendered:
            sys.stderr.write(f'{TARGET} is stale; run {Path(__file__).name} without --check\n')
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(rendered, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
