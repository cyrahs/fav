"""Dump the database schema the Python baseline creates, for the Rust schema check (WP1).

Python has no schema file: every source creates its own tables, in its own
`_ensure_table()` or `_ensure_schema()`, the first time it runs. This tool calls every
one of them, through the real Python code, against a fresh temporary database, then
describes what they left behind with `describe.sql`. fav-db's schema test applies the
consolidated Rust schema to another fresh database, runs the same query, and compares
the result with the committed file line for line.

    FAV_TEST_DATABASE_URL=postgresql://tests@127.0.0.1:5432/fav-tests \\
        UV_PYTHON=3.12 uv run python rust/tools/schema/dump_schema.py          # rewrite rust/parity/schema.txt
    ... uv run python rust/tools/schema/dump_schema.py --check                 # what CI runs

`FAV_TEST_DATABASE_URL` names a database the tool may connect to and create databases
from; the schema is created in a temporary database that is dropped afterwards.
"""

from __future__ import annotations

import argparse
import asyncio
import difflib
import os
import sys
import tempfile
import uuid
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

HERE = Path(__file__).resolve().parent
RUST_DIR = HERE.parents[1]
REPO_ROOT = RUST_DIR.parent
OUTPUT = RUST_DIR / 'parity' / 'schema.txt'
DESCRIBE_SQL = HERE / 'describe.sql'
HEADER = '# Generated by rust/tools/schema/dump_schema.py from the Python baseline; do not edit.\n'


def _with_database(url: str, name: str) -> str:
    parts = urlsplit(url)
    return urlunsplit((parts.scheme, parts.netloc, f'/{name}', parts.query, parts.fragment))


def _create_python_schema() -> None:
    """Run every schema-creating function of the baseline, in the order a fresh deployment would."""
    # Imported here: src.core.env reads POSTGRES_DSN at import time, which main() sets first.
    from src.api import live2d_overrides  # noqa: PLC0415
    from src.core import settings  # noqa: PLC0415
    from src.tool import (  # noqa: PLC0415
        control_queue,
        database,
        hanime1_author,
        hanime1_series,
        notifications,
        site_sessions,
        telegram_queue,
    )
    from src.web import azurlane, bd2, bilibili, hanime1, jandan, kemono, nikke, pixiv, rednote, telegram, twitter, wechat  # noqa: PLC0415

    settings.ensure_table_sync(force=True)
    live2d_overrides.PostgresLive2DViewOverrideStore(os.environ['POSTGRES_DSN'])._ensure_schema()  # noqa: SLF001

    async def _async_parts() -> None:
        await control_queue.ensure_control_requests_table()
        await notifications.ensure_notifications_table()
        await site_sessions.ensure_table()
        await telegram_queue.ensure_telegram_media_queue_table()
        await hanime1_series.ensure_hanime1_series_tables()
        await hanime1_author.ensure_hanime1_author_tables()
        # The source classes' schema methods do not read instance state, so they are
        # called on bare instances: their constructors build HTTP clients and browsers.
        for cls, method in (
            (bilibili.Bilibili, '_ensure_table'),
            (telegram.Telegram, '_initialize_tables'),
            (nikke.Nikke, '_ensure_schema'),
            (bd2.BD2, '_ensure_schema'),
            (azurlane.AzurLane, '_ensure_schema'),
            (hanime1.Hanime1, '_ensure_table'),
            (jandan.Jandan, '_ensure_table'),
            (kemono.Kemono, '_ensure_table'),
            (twitter.Twitter, '_ensure_table'),
            (pixiv.Pixiv, '_ensure_table'),
            (rednote.RedNote, '_ensure_table'),
            (wechat.Wechat, '_ensure_table'),
        ):
            instance = cls.__new__(cls)
            await getattr(instance, method)()
            # Hanime1.__del__ cleans up a temporary directory only its constructor makes.
            instance.__dict__.setdefault('_tmp_dir', tempfile.TemporaryDirectory(prefix='fav-schema-'))
        await database.close_pool()

    asyncio.run(_async_parts())


def _describe(dsn: str) -> str:
    import psycopg  # noqa: PLC0415

    with psycopg.connect(dsn, autocommit=True) as conn, conn.cursor() as cursor:
        cursor.execute(DESCRIBE_SQL.read_text(encoding='utf-8'))
        return HEADER + ''.join(f'{row[0]}\n' for row in cursor.fetchall())


def build(admin_url: str) -> str:
    import psycopg  # noqa: PLC0415

    name = f'fav_schema_py_{uuid.uuid4().hex[:12]}'
    with psycopg.connect(admin_url, autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{name}"')
    dsn = _with_database(admin_url, name)
    try:
        os.environ['POSTGRES_DSN'] = dsn
        os.environ.setdefault('API_TOKEN', 'token-for-schema-dump')
        sys.path.insert(0, str(REPO_ROOT))
        _create_python_schema()
        return _describe(dsn)
    finally:
        with psycopg.connect(admin_url, autocommit=True) as conn:
            conn.execute(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)')


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n', 1)[0])
    parser.add_argument('--check', action='store_true', help='compare with the committed file instead of writing it')
    args = parser.parse_args()
    admin_url = os.environ.get('FAV_TEST_DATABASE_URL', '').strip()
    if not admin_url:
        print('FAV_TEST_DATABASE_URL is not set')
        return 2
    generated = build(admin_url)
    if args.check:
        committed = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if committed == generated:
            print(f'{OUTPUT.relative_to(REPO_ROOT)} matches the Python baseline ({generated.count(chr(10)) - 1} lines)')
            return 0
        print(f'{OUTPUT.relative_to(REPO_ROOT)} differs from what the Python baseline creates:')
        diff = difflib.unified_diff(committed.splitlines(), generated.splitlines(), 'committed', 'generated', lineterm='', n=0)
        for line in list(diff)[:60]:
            print(f'  {line}')
        return 1
    OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT.relative_to(REPO_ROOT)}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
